# -*- coding: utf-8 -*-
"""Fetch month-of-year observation counts from iNaturalist for every edible species, limited to the
Pacific Northwest (British Columbia, Washington, Oregon), and write src/data/seasonality.py.

Run by hand when you want fresh numbers (needs network); the site build only reads the saved file:
    python3 src/fetch_seasonality.py
    python3 src/fetch_seasonality.py --last-only   # only add/refresh each species' latest observation date
    python3 src/fetch_seasonality.py --region-years   # only add/refresh records per year in each region
"""
import json
import re
import sys
import time
import urllib.parse
import urllib.request
from datetime import date
from pathlib import Path

SRC = Path(__file__).resolve().parent
sys.path.insert(0, str(SRC))
from data.book import GROUPS  # noqa: E402
from data.north_america import NA_SPECIES  # noqa: E402

API = "https://api.inaturalist.org/v1"
PLACES = "7085,46,10"  # British Columbia, Washington, Oregon
REGIONS = {"bc": 7085, "wa": 46, "or": 10}
UA = "mushroom-guide/1.0 (+https://github.com/bbpouq/mushroom-guide)"

# Book (European) names whose Pacific Northwest counterpart is a different taxon (see NA_SPECIES_NOTES).
PNW_TAXON = {
    "Tricholoma matsutake": "Tricholoma murrillianum",
    "Sparassis crispa": "Sparassis radicata",
    "Laetiporus sulphureus": "Laetiporus conifericola",
    "Hydnum repandum": "Hydnum",
    "Armillaria mellea": "Armillaria",
    "Morchella esculenta": "Morchella",
    "Pleurotus ostreatus": "Pleurotus",
}
# Book species that have their own Pacific Northwest entry; their local records belong to that entry.
SKIP = {"Cantharellus cibarius"}


def slug(latin):  # same rule as build_site.slug
    return re.sub(r"[^a-z0-9]+", "-", latin.split(" / ")[0].replace(" spp.", "").lower()).strip("-")


def get(path, **params):
    req = urllib.request.Request(f"{API}/{path}?{urllib.parse.urlencode(params)}", headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def taxon(name):
    """Return (id, current iNaturalist name); falls back to a match on a synonym (e.g. Lepista nuda -> Collybia nuda)."""
    res = get("taxa", q=name, is_active="true", per_page=10)["results"]
    for t in res:
        if t["name"] == name:
            return t["id"], t["name"]
    for t in res:
        if t.get("matched_term") == name and t["rank"] in ("species", "genus"):
            return t["id"], t["name"]
    return None, None


def last_seen(tid):
    """Date of the most recent research-grade observation in BC/WA/OR ("" if none)."""
    res = get("observations", taxon_id=tid, place_id=PLACES, quality_grade="research", order_by="observed_on",
              order="desc", per_page=1)["results"]
    return (res[0].get("observed_on") or "") if res else ""


def write(out, fetched):
    body = (f'# -*- coding: utf-8 -*-\n"""iNaturalist research-grade observations per month in BC, Washington and Oregon.\n'
            f'Generated by src/fetch_seasonality.py on {fetched}; do not edit by hand."""\n\n'
            f'FETCHED = "{fetched}"\nPLACES = "{PLACES}"\nSEASONALITY = {{\n')
    body += "".join(f" {k!r}: dict(taxon={v['taxon']!r}, taxon_id={v['taxon_id']}, counts={v['counts']}, "
                    f"regions={v['regions']!r}, years={v['years']!r}, last={v.get('last', '')!r}, ryears={v.get('ryears', {})!r}),\n" for k, v in out.items())
    body += "}\n"
    (SRC / "data" / "seasonality.py").write_text(body, encoding="utf-8")
    print(f"wrote src/data/seasonality.py ({len(out)} species)")


def region_years(tid):
    """Records per year in each region (BC, WA, OR), for the coverage shown per region."""
    out = {}
    for key, place in REGIONS.items():
        time.sleep(1)
        hy = get("observations/histogram", taxon_id=tid, place_id=place, quality_grade="research",
                 date_field="observed", interval="year")["results"]["year"]
        out[key] = {k[:4]: v for k, v in sorted(hy.items()) if v}
    return out


def region_years_only():
    from data.seasonality import SEASONALITY, FETCHED
    out = {}
    for k, v in SEASONALITY.items():
        out[k] = dict(v, ryears=region_years(v["taxon_id"]))
        print(k, {r: len(y) for r, y in out[k]["ryears"].items()})
    write(out, FETCHED)


def last_only():
    from data.seasonality import SEASONALITY, FETCHED
    out = {}
    for k, v in SEASONALITY.items():
        out[k] = dict(v, last=last_seen(v["taxon_id"]))
        print(f"{out[k]['last']:>10}  {k}")
        time.sleep(1)
    write(out, FETCHED)


def main():
    if "--last-only" in sys.argv:
        return last_only()
    if "--region-years" in sys.argv:
        return region_years_only()
    names = [s["latin"] for s in NA_SPECIES] + [sp[2] for _, _, items in GROUPS for sp in items]
    out = {}
    for latin in names:
        if latin in SKIP:
            continue
        name = PNW_TAXON.get(latin) or latin.split(" / ")[0].replace(" spp.", "")
        tid, inat_name = taxon(name)
        time.sleep(1)
        if not tid:
            print(f"  no taxon: {name}")
            continue
        h = get("observations/histogram", taxon_id=tid, place_id=PLACES, quality_grade="research",
                date_field="observed", interval="month_of_year")["results"]["month_of_year"]
        counts = [h.get(str(m), 0) for m in range(1, 13)]
        regions = {}
        for key, place in REGIONS.items():  # the same counts for each region on its own
            time.sleep(1)
            hr = get("observations/histogram", taxon_id=tid, place_id=place, quality_grade="research",
                     date_field="observed", interval="month_of_year")["results"]["month_of_year"]
            regions[key] = [hr.get(str(m), 0) for m in range(1, 13)]
        time.sleep(1)
        hy = get("observations/histogram", taxon_id=tid, place_id=PLACES, quality_grade="research",
                 date_field="observed", interval="year")["results"]["year"]
        years = {k[:4]: v for k, v in sorted(hy.items()) if v}
        time.sleep(1)
        out[slug(latin)] = dict(taxon=inat_name, taxon_id=tid, counts=counts, regions=regions, years=years, last=last_seen(tid), ryears=region_years(tid))
        print(f"{sum(counts):6d}  {latin}  ->  {inat_name}")
        time.sleep(1)
    write(out, date.today().isoformat())


if __name__ == "__main__":
    main()
